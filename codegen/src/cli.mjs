function writeOrCheck(targetPath, content) {
  if (checkOnly) {
    if (!fs.existsSync(targetPath)) {
      console.error(`[sarvam-gen --check] Missing generated file: ${targetPath}`);
      process.exitCode = 1;
      return;
    }
    const existing = fs.readFileSync(targetPath, 'utf8');
    if (existing !== content) {
      console.error(`[sarvam-gen --check] Drift detected in: ${targetPath}`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, content, 'utf8');
  console.log(`[sarvam-gen] Wrote ${path.relative(ROOT, targetPath)}`);
}

const openapi = loadJson(OPENAPI_PATH);
const asyncapi = loadJson(ASYNCAPI_PATH);
const metadata = loadJson(METADATA_PATH);
const ir = buildNormalizedIr(openapi, asyncapi, metadata);

writeOrCheck(IR_OUTPUT_PATH, JSON.stringify(ir, null, 2) + '\n');
writeOrCheck(
  path.join(ROOT, 'packages/kotlin/sarvam-core/src/main/kotlin/ai/sarvam/generated/SarvamSpecGenerated.kt'),
  renderKotlin(ir)
);
writeOrCheck(
  path.join(ROOT, 'packages/swift/Sources/Sarvam/Generated/SarvamSpecGenerated.swift'),
  renderSwift(ir)
);
writeOrCheck(
  path.join(ROOT, 'packages/ts-core/src/generated/sarvamSpecGenerated.ts'),
  renderTypeScript(ir)
);
writeOrCheck(
  path.join(ROOT, 'packages/dart/sarvam/lib/src/generated/sarvam_spec_generated.dart'),
  renderDart(ir)
);

if (checkOnly && !process.exitCode) {
  console.log('[sarvam-gen --check] All generated artifacts are up-to-date.');
}
