function renderSwift(ir) {
  const makeOpenStruct = (name, values) => {
    const props = values
      .map((v) => `    public static let ${toCamelCase(v)} = ${name}(rawValue: "${v}")`)
      .join('\n');
    return `public struct ${name}: RawRepresentable, Codable, Sendable, Hashable, ExpressibleByStringLiteral {
    public let rawValue: String
    public init(rawValue: String) { self.rawValue = rawValue }
    public init(stringLiteral value: String) { self.rawValue = value }
    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        self.rawValue = try container.decode(String.self)
    }
    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        try container.encode(rawValue)
    }
${props}
}`;
  };

  const opEntries = ir.operations
    .map(
      (op) =>
        `        "${op.operationId}": OperationSpec(operationId: "${op.operationId}", resourceGroup: "${op.resourceGroup}", methodName: "${op.methodName}", httpMethod: "${op.httpMethod}", path: "${op.path}", operationKind: .${toCamelCase(op.operationKind)}, environmentHost: .${op.environmentHost}, streamingMode: "${op.streamingMode}")`
    )
    .join(',\n');

  return `// AUTO-GENERATED BY sarvam-gen (${ir.generator}) — DO NOT EDIT MANUALLY.
// Source Spec Version: ${ir.specVersion}
import Foundation

public enum SarvamSpecMetadata {
    public static let sdkVersion = "0.1.0"
    public static let specVersion = "${ir.specVersion}"
    public static let defaultApiBaseUrl = "${ir.environments.api}"
    public static let defaultDubbingBaseUrl = "${ir.environments.dubbing}"
    public static let defaultWsBaseUrl = "${ir.environments.ws}"

    public static let operations: [String: OperationSpec] = [
${opEntries}
    ]
}

public enum OperationKind: String, Sendable, Codable {
    case idempotent = "IDEMPOTENT"
    case statelessPost = "STATELESS_POST"
    case multipartCompute = "MULTIPART_COMPUTE"
    case jobCreate = "JOB_CREATE"
}

public enum EnvironmentHost: String, Sendable, Codable {
    case api = "api"
    case dubbing = "dubbing"
    case ws = "ws"
}

public struct OperationSpec: Sendable, Equatable {
    public let operationId: String
    public let resourceGroup: String
    public let methodName: String
    public let httpMethod: String
    public let path: String
    public let operationKind: OperationKind
    public let environmentHost: EnvironmentHost
    public let streamingMode: String

    public init(
        operationId: String,
        resourceGroup: String,
        methodName: String,
        httpMethod: String,
        path: String,
        operationKind: OperationKind,
        environmentHost: EnvironmentHost,
        streamingMode: String
    ) {
        self.operationId = operationId
        self.resourceGroup = resourceGroup
        self.methodName = methodName
        self.httpMethod = httpMethod
        self.path = path
        self.operationKind = operationKind
        self.environmentHost = environmentHost
        self.streamingMode = streamingMode
    }
}

${makeOpenStruct('LanguageCode', ir.enums.LanguageCode)}

${makeOpenStruct('TtsModel', ir.enums.TtsModel)}

${makeOpenStruct('SttModel', ir.enums.SttModel)}

${makeOpenStruct('ChatModel', ir.enums.ChatModel)}

${makeOpenStruct('Speaker', ir.enums.Speaker)}

${makeOpenStruct('AudioCodec', ir.enums.AudioCodec)}

${makeOpenStruct('SttMode', ir.enums.SttMode)}
`;
}

function renderTypeScript(ir) {
  const makeTsEnum = (name, values) => {
    const union = values.map((v) => `'${v}'`).join(' | ');
    const constEntries = values.map((v) => `  ${toUpperSnake(v)}: '${v}' as const`).join(',\n');
    return `export type ${name} = ${union} | (string & {});\nexport const ${name} = {\n${constEntries}\n} as const;`;
  };

  const opsJson = JSON.stringify(
    Object.fromEntries(ir.operations.map((op) => [op.operationId, op])),
    null,
    2
  );

  return `/* node:coverage disable */
// AUTO-GENERATED BY sarvam-gen (${ir.generator}) — DO NOT EDIT MANUALLY.
// Source Spec Version: ${ir.specVersion}

export const SARVAM_SDK_VERSION = '0.1.0';
export const SARVAM_SPEC_VERSION = '${ir.specVersion}';
export const DEFAULT_API_BASE_URL = '${ir.environments.api}';
export const DEFAULT_DUBBING_BASE_URL = '${ir.environments.dubbing}';
export const DEFAULT_WS_BASE_URL = '${ir.environments.ws}';

export type OperationKind = 'IDEMPOTENT' | 'STATELESS_POST' | 'MULTIPART_COMPUTE' | 'JOB_CREATE';
export type EnvironmentHost = 'api' | 'dubbing' | 'ws';

export interface OperationSpec {
  readonly operationId: string;
  readonly resourceGroup: string;
  readonly methodName: string;
  readonly httpMethod: string;
  readonly path: string;
  readonly priority: string;
  readonly operationKind: OperationKind;
  readonly environmentHost: EnvironmentHost;
  readonly streamingMode: string;
  readonly summary: string;
  readonly quirks: Record<string, unknown>;
}

export const SARVAM_OPERATIONS: Record<string, OperationSpec> = ${opsJson};

${makeTsEnum('LanguageCode', ir.enums.LanguageCode)}

${makeTsEnum('TtsModel', ir.enums.TtsModel)}

${makeTsEnum('SttModel', ir.enums.SttModel)}

${makeTsEnum('ChatModel', ir.enums.ChatModel)}

${makeTsEnum('Speaker', ir.enums.Speaker)}

${makeTsEnum('AudioCodec', ir.enums.AudioCodec)}

${makeTsEnum('SttMode', ir.enums.SttMode)}
`;
}

